"""Writes src/net/RootCAs.h: the root CAs the firmware trusts for HTTPS to
GitHub (github.com and its release download host), taken from a Mozilla-derived
CA bundle.

Re-run if GitHub moves to a CA not listed in ROOTS (update checks then fail
with a TLS error; uploads from the PC still work):

    python scripts/gen_root_cas.py [path/to/ca-bundle.pem]

Default bundle: certifi's if installed, else Git for Windows'. Firmware
signatures, not TLS, decide what gets installed; TLS keeps the downloads
honest and the update checks trustworthy.
"""

import sys
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import serialization
from cryptography.x509.oid import NameOID

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "src" / "net" / "RootCAs.h"

# Subject CNs. github.com chains to Sectigo (cross-signed by USERTrust ECC);
# release-assets.githubusercontent.com to Let's Encrypt (ISRG). The RSA and
# DigiCert roots cover GitHub's other recent chains.
ROOTS = [
    "USERTrust ECC Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "USERTrust RSA Certification Authority",
    "ISRG Root X1",
    "ISRG Root X2",
    "DigiCert Global Root G2",
]


def default_bundle() -> Path:
    try:
        import certifi
        return Path(certifi.where())
    except ImportError:
        return Path(r"C:\Program Files\Git\mingw64\etc\ssl\certs\ca-bundle.crt")


def main():
    bundle = Path(sys.argv[1]) if len(sys.argv) > 1 else default_bundle()
    certs = x509.load_pem_x509_certificates(bundle.read_bytes())
    by_cn = {}
    for cert in certs:
        cns = cert.subject.get_attributes_for_oid(NameOID.COMMON_NAME)
        if cns:
            by_cn.setdefault(cns[0].value, cert)

    missing = [cn for cn in ROOTS if cn not in by_cn]
    if missing:
        sys.exit(f"Not in {bundle}: {', '.join(missing)}")

    lines = []
    for cn in ROOTS:
        cert = by_cn[cn]
        lines.append(f"    // {cn} (expires {cert.not_valid_after_utc:%Y-%m-%d})")
        pem = cert.public_bytes(serialization.Encoding.PEM).decode().strip().splitlines()
        lines.extend(f'    "{line}\\n"' for line in pem)

    OUT.write_text(
        "#pragma once\n\n"
        "// Root CAs trusted for HTTPS to GitHub (release checks and downloads).\n"
        "// Generated by scripts/gen_root_cas.py from a Mozilla-derived CA bundle; re-run\n"
        "// it if GitHub moves to a CA not listed here.\n"
        "static const char GITHUB_ROOT_CAS[] =\n" + "\n".join(lines) + ";\n")
    print(f"Wrote {OUT.relative_to(REPO)} with {len(ROOTS)} roots from {bundle}")


if __name__ == "__main__":
    main()
